#!/usr/bin/env python3
"""Context packet from the session-plan index: Approach first, then core bodies, then candidates.

    python tools/slice.py expand                 packet into this run's summary file
    python tools/slice.py expand --check         resolve every core and candidate item; write nothing; FAIL lists the bad ones
    python tools/slice.py expand --out session-context.md   write the packet file (slice.py open does this before launch)
    python tools/slice.py expand --only K2,C3    just those items' bodies (open a candidate on demand)
The default budget is high so a closed core is pasted, not dropped. Bodies past --budget characters are listed, not
pasted (open them with --only). Kept sections that are still the seed placeholder are omitted. The index format is
plan_index.py; `slice.py adjust` is the only writer of the index and of `## Approach`. --selftest runs the cases in a temp repo.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # tools/lib; boot adds every area dir
import boot  # noqa: E402,F401

import agent_log
import md_format_lib as md
import plan_index as pi

PLAN = "session-plan.md"
BUDGET = 2_000_000  # a closed core is pasted; gather focus is the cap, not a silent drop
_TRUST = "Check this against the core bodies. If they disagree, trust the code and `slice.py adjust approach`, then edit."

def load(root: Path) -> pi.Index:
    path = root / PLAN
    if not path.is_file():
        agent_log.fail("no session-plan.md here; `python tools/slice.py plan` writes the seed first")
    gathered = pi.split_plan(md.read_text(path))[1]
    if not gathered:
        agent_log.fail("session-plan.md has no `<!-- gathered -->` index; `python tools/slice.py plan --refresh` rebuilds it")
    return pi.parse(gathered)

def check(root: Path, idx: pi.Index) -> list[str]:
    bad = [f"{it.id} {it.kind} `{it.ref}`: {err}" for it in idx.items if (err := pi.resolve(root, it)[0])]
    bad += [f"{it.id}: candidate without a condition" for it in idx.items if not it.core and not it.note]
    if not any(it.core for it in idx.items):
        bad.append("the index has no core items")
    return bad

def _sections(head: str) -> list[tuple[str, str]]:
    lines = head.splitlines()
    idxs = [i for i, ln in enumerate(lines) if ln.startswith("## ")]
    out: list[tuple[str, str]] = []
    for n, i in enumerate(idxs):
        end = idxs[n + 1] if n + 1 < len(idxs) else len(lines)
        out.append((lines[i].strip(), "\n".join(lines[i + 1:end]).strip()))
    return out

def _plan_notes(root: Path) -> list[str]:
    """Real kept sections, Approach first. Seed placeholders are omitted (they are not notes)."""
    import session_plan as sp
    head = md.read_text(root / PLAN).split(pi.MARKER, 1)[0]
    skip = {body.strip() for _, body in sp.KEPT_HEADS}
    real = [(t, b) for t, b in _sections(head) if b.strip() and b.strip() not in skip]
    ordered = [s for s in real if s[0] == "## Approach"] + [s for s in real if s[0] != "## Approach"]
    if not ordered:
        return []
    lines = ["## Plan", ""]
    for title, body in ordered:
        lines += [f"### {title[3:].strip()}", "", body.strip(), ""]
        if title == "## Approach":
            lines += [_TRUST, ""]
    return lines

def _body(root: Path, it: pi.Item) -> list[str]:
    err, lines = pi.resolve(root, it)
    note = f" - {it.note}" if it.note else ""
    loc = f" {lines[0]}" if lines and lines[0].startswith("(L") else ""
    head = f"#### {it.id} {it.kind} `{it.ref}`{note}{loc}".rstrip()
    rest = lines[1:] if lines and lines[0].startswith("(L") else lines
    if err:
        return [head, f"UNRESOLVED: {err}", ""]
    fence = it.kind in ("func", "file") or (it.kind == "doc" and not it.ref.split("#")[0].endswith(".md"))
    return [head] + (["```"] + rest + ["```"] if fence else rest) + [""]

def packet(root: Path, idx: pi.Index, only: list[str], budget: int) -> tuple[str, list[str]]:
    """(packet text, ids listed but not pasted because of the budget)."""
    out = ["# Session context (generated by `slice.py expand`; do not edit, change the index with `slice.py adjust`)", ""]
    if not only:
        out += _plan_notes(root)
    out += [f"- {k}: {v}" for k, v in idx.identity] + [""]
    skipped: list[str] = []
    picked = [idx.find(t) for t in only] if only else [it for it in idx.items if it.core]
    missing = [t for t, it in zip(only, picked) if it is None] if only else []
    used = 0
    out += ["## Core" if not only else "## Requested", ""]
    for it in [p for p in picked if p is not None]:
        body = _body(root, it)
        size = sum(len(x) + 1 for x in body)
        if used + size > budget and used:
            skipped.append(it.id)
            out += [f"#### {it.id} {it.kind} `{it.ref}` - over budget, open with `slice.py expand --only {it.id}`", ""]
            continue
        used += size
        out += body
    out += [f"UNKNOWN id/ref: {t}" for t in missing]
    if not only:
        cands = [it for it in idx.items if not it.core]
        out += ["## Candidates (open with `slice.py expand --only ID` or `wdb__lookup action=packet query=ID` when the condition holds)", ""]
        out += [f"- {it.id} {it.kind} `{it.ref}` - when: {it.note}" for it in cands] or ["(none)"]
        out += ["", "## Card", "", idx.card or "(no card)"]
    return "\n".join(out).rstrip() + "\n", skipped

def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--selftest" in argv:
        return selftest()
    ap = agent_log.std_parser("Build or validate the context packet from the session-plan index.")
    ap.add_argument("--check", action="store_true", help="Resolve every item; write nothing; FAIL lists unresolved items.")
    ap.add_argument("--out", default="", help="Write the packet to this file (relative to the root), e.g. session-context.md.")
    ap.add_argument("--only", default="", help="Comma list of item ids or refs to expand (candidates too).")
    ap.add_argument("--budget", type=int, default=BUDGET, help=f"Characters of core bodies before the rest are listed only (default {BUDGET}).")
    ap.add_argument("--selftest", action="store_true", help="Run the cases in a temp repo.")
    args = ap.parse_args(argv)
    root = agent_log.resolve_root(args)
    idx = load(root)
    if args.check:
        bad = check(root, idx)
        body = "\n".join(bad) if bad else f"index ok: {len(idx.items)} items resolve"  # problems are never folded
        return agent_log.finish("plan-expand", root, body, "FAIL" if bad else "PASS", args=args, check=1, unresolved=len(bad))
    text, skipped = packet(root, idx, agent_log.split_list([args.only]), args.budget)
    status = "FAIL" if "UNRESOLVED:" in text or "UNKNOWN id/ref:" in text else "PASS"
    echo = f"packet: {len(text.splitlines())} lines, {len(text)} chars" + (f"; over budget, listed only: {' '.join(skipped)}" if skipped else "")
    if args.out:
        md.write_text(root / args.out, text)
        echo += f"; wrote {args.out}"
    return agent_log.finish("plan-expand", root, text, status, args=args, echo=echo, lines=len(text.splitlines()),
                            skipped=len(skipped) or None)

def selftest() -> int:
    import subprocess
    import tempfile

    import repo_lib

    bad: list[str] = []
    with tempfile.TemporaryDirectory() as td:
        root = repo_lib.selftest_repo(td, empty_commit=True)
        (root / "scripts").mkdir(exist_ok=True)
        (root / "design").mkdir(exist_ok=True)
        (root / "scripts" / "demo.gd").write_text("extends Node\n\nfunc alpha() -> void:\n\tpass\n\nfunc beta() -> void:\n\tpass\n", encoding="utf-8")
        (root / "design" / "demo.md").write_text("# Demo\n\n## Rules\n\nRule text.\n\n## Other\n\nOther text.\n", encoding="utf-8")
        idx = pi.Index(identity=[("door", "demo")], card="card line", items=[
            pi.Item("C1", "func", "scripts/demo.gd:alpha", True, "edited"),
            pi.Item("C2", "doc", "design/demo.md#Rules", True, "rules"),
            pi.Item("K3", "names", "scripts/demo.gd", False, "the change reaches Demo code")])
        plan = root / PLAN
        plan.write_text("# Session plan\n\n" + pi.MARKER + "\n\n" + pi.render(idx), encoding="utf-8")

        def run(*a: str) -> tuple[int, str]:
            p = subprocess.run([*boot.cmd("plan_expand"), "--root", str(root), *a], capture_output=True, text=True)
            return p.returncode, p.stdout + p.stderr

        code, out = run("--check")
        if code or (root / "session-context.md").exists():
            bad.append(f"--check passes on a good index and writes no packet: {out}")
        code, out = run("--out", "session-context.md")
        got = (root / "session-context.md").read_text(encoding="utf-8") if (root / "session-context.md").is_file() else ""
        if code or "func alpha" not in got or "Rule text." not in got or "Other text." in got or "func beta" in got:
            bad.append("the packet pastes core bodies only (the function and the heading section)")
        if "K3 names `scripts/demo.gd` - when: the change reaches Demo code" not in got or "card line" not in got:
            bad.append("the packet lists candidates with their condition and the card")
        if BUDGET < 1_000_000:
            bad.append("the default budget must paste a closed core, not drop it")
        import session_plan as sp
        placeholder = dict(sp.KEPT_HEADS)["## Outcome"]
        plan.write_text("# Session plan\n\n## Outcome\n\n" + placeholder + "\n\n## Open questions\n\n- none yet\n\n"
                        "## Approach\n\nedit alpha first\n\n" + pi.MARKER + "\n\n" + pi.render(idx), encoding="utf-8")
        code, out = run("--out", "session-context.md")
        got = (root / "session-context.md").read_text(encoding="utf-8")
        if code or "edit alpha first" not in got or _TRUST not in got or placeholder in got or "- none yet" in got:
            bad.append("the packet leads with a real Approach, the trust line, and no seed placeholder")
        approach_at, core_at = got.find("### Approach"), got.find("## Core")
        if approach_at < 0 or core_at < 0 or approach_at > core_at or "- edited" not in got:
            bad.append("Approach comes before the core, and a core heading carries its why-note")
        code, out = run("--only", "K3")
        summ = agent_log.agent_summary_path("plan-expand", root).read_text(encoding="utf-8")
        if code or "alpha, beta" not in summ:
            bad.append("--only expands a candidate on demand")
        code, out = run("--budget", "10")
        if "over budget" not in agent_log.agent_summary_path("plan-expand", root).read_text(encoding="utf-8"):
            bad.append("core past --budget is listed, not pasted")
        err, body = pi.resolve(root, pi.Item("C9", "doc", "design/demo.md", True, "range", (5, 5)))
        if err or body != ["(L5-5)", "Rule text."]:
            bad.append(f"a doc item with a line range resolves to those lines only: {err or body}")
        idx.items.append(pi.Item("C4", "func", "scripts/demo.gd:gone", True, "x"))
        plan.write_text("# Session plan\n\n" + pi.MARKER + "\n\n" + pi.render(idx), encoding="utf-8")
        (root / "session-context.md").unlink()
        code, out = run("--check")
        if code == 0 or "C4" not in out or (root / "session-context.md").exists():
            bad.append(f"--check fails on an unresolved item, naming it, and leaves no packet: {out}")
    return agent_log.selftest_result(bad)

if __name__ == "__main__":
    raise SystemExit(agent_log.guarded(main))
