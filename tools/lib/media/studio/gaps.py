"""Write the Build gap list from the studio registry: a full reference file and the task's
"UI gaps for Build" section. `media.py studio --gaps` writes both; `--gaps --check` fails when stale."""
from __future__ import annotations

from pathlib import Path

from media.pipeline import store

from . import registry as R

REF = Path("design/refs/unified-content-pipeline/studio-build-gaps.md")
TASK = Path("design/tasks/unified-content-pipeline.md")
HEAD = "## UI gaps for Build"
SRC = "`tools/lib/media/studio/registry.py`"
CMD = "`python tools/media.py studio --gaps`"


def _uses() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for t in store.TYPES:
        for sid in ["start", *R.TYPES[t]["steps"], "export"]:
            for a in R.step_spec(t, sid)["actions"]:
                out.setdefault(a, []).append(f"{t}/{sid}")
    return out


def _recipes() -> list[tuple[str, list[str]]]:
    rows = []
    for t in store.TYPES:
        for sid in R.TYPES[t]["steps"]:
            acts = [a for a in R.step_spec(t, sid)["actions"] if R.ACTIONS[a].get("recipe")]
            if acts and R.recipe_key(t, sid) not in R.RECIPES_READY:
                rows.append((R.recipe_key(t, sid), acts))
    return rows


def _cell(s: object) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _field_names(fields: list[dict]) -> str:
    out = []
    for fd in fields:
        name = fd["key"] + ("*" if fd.get("required") else "")
        if fd.get("columns"):
            name += "[" + ", ".join(c["key"] for c in fd["columns"]) + "]"
        if fd.get("fields"):
            name += "{" + ", ".join(c["key"] for c in fd["fields"]) + "}"
        out.append(name)
    return ", ".join(out)


def ref_text() -> str:
    uses = _uses()
    lines = [
        "# Studio: what is left to build", "",
        f"Generated by {CMD} from {SRC}. Do not edit by hand; change the registry and regenerate.",
        "The studio page shows the same list under Coverage, Left to build. In real mode each missing piece answers 501 `not_wired=<seam>` and the page says \"not set up yet\"; simulate fakes it.", "",
        "## Model setups", "",
        "| Setup | Models | Status | Used by actions | Note |", "|---|---|---|---|---|",
    ]
    for sid, s in R.SETUPS.items():
        users = sorted(a for a, spec in R.ACTIONS.items() if spec["setup"] == sid)
        lines.append(f"| `{sid}` {s['label']} | {_cell(s['models'])} | {s['status']} | {', '.join(users) or '-'} | {_cell(s['note'])} |")
    lines += ["", "## Actions", "", "| Action | Command the studio expects | Inputs | Output | Setup | Wired | Steps |", "|---|---|---|---|---|---|---|"]
    for a, s in R.ACTIONS.items():
        lines.append(f"| `{a}` {s['label']} | `{_cell(s['command'])}` | {_cell(s['inputs'])} | `{_cell(s['outputs'])}` | {s['setup'] or '-'} | "
                     f"{'yes' if s['wired'] else 'no'}{' (needs recipe)' if s.get('recipe') else ''} | {len(uses.get(a, []))} |")
    rec = _recipes()
    lines += ["", f"## Default recipes to write ({len(rec)})", "",
              "A recipe is the workflow and step prompt an action uses for that type and step. Real mode needs one before `generate`, `tune`, `variant`, `icon`, `tile` or `keyframes` can run there.", ""]
    lines += [f"- `{k}`: {', '.join(v)}" for k, v in rec]
    lines += ["", "## Steps per type", "", "`*` marks a field the step needs before it can be approved. Needs: pictures = one approved picture, mesh = an approved 3D model, clips = an approved animation for every listed clip.", ""]
    for t in store.TYPES:
        lines += [f"### {t}", "", f"Grounded in: {R.TYPES[t]['source']}.", "", "| Step | Fields | Actions (not set up in real mode) | Needs | Group |", "|---|---|---|---|---|"]
        for sid in ["start", *R.TYPES[t]["steps"], "export"]:
            st = R.step_spec(t, sid)
            acts = [a + ("" if R.available(a, t, sid, False)[0] else " (no)") for a in st["actions"]]
            lines.append(f"| {sid} | {_cell(_field_names(st['fields'])) or '-'} | {', '.join(acts) or '-'} | {', '.join(st['needs']) or 'fields'} | {st['group'] or '-'} |")
        opens = [(sid, st["open"]) for sid, st in R.TYPES[t]["steps"].items() if st["open"]]
        lines += [""] + [f"Open: {sid}: {q}" for sid, q in opens] + ([""] if opens else [])
    lines += ["## Other seams", ""] + [f"- `{s['id']}`: {s['want']} Seam: `{s['seam']}`." for s in R.SEAMS]
    return "\n".join(lines).rstrip() + "\n"


def task_section() -> str:
    missing = [k for k, s in R.SETUPS.items() if s["status"] != "ready"]
    not_wired = [a for a, s in R.ACTIONS.items() if not s["wired"]]
    lines = [
        HEAD,
        f"Generated by {CMD} from {SRC}. The full list per type, step and action, with commands, inputs, outputs and setups: [studio-build-gaps](../refs/unified-content-pipeline/studio-build-gaps.md). "
        "In real mode each gap answers 501 `not_wired=<seam>` and the page says \"not set up yet\"; simulate fakes it.", "",
        f"- Actions not wired ({len(not_wired)}): {', '.join(f'`{a}`' for a in not_wired)}.",
        f"- Default recipes to write: {len(_recipes())} type/step pairs.",
        f"- Model setups to build or finish ({len(missing)}):",
    ]
    lines += [f"  - `{k}` {R.SETUPS[k]['label']} ({R.SETUPS[k]['status']}): {R.SETUPS[k]['models']}." for k in missing]
    lines += ["- Seams:"] + [f"  - `{s['id']}`: {s['want']}" for s in R.SEAMS]
    return "\n".join(lines) + "\n"


def _splice(text: str, section: str) -> str:
    i = text.index(HEAD)
    j = text.find("\n## ", i + len(HEAD))
    tail = text[j + 1:] if j >= 0 else ""
    return text[:i] + section + ("\n" + tail if tail else "")


def write(repo: Path, check: bool = False) -> list[str]:
    """Paths that are (or were) stale."""
    stale = []
    want_ref = ref_text()
    ref = repo / REF
    if not ref.is_file() or ref.read_text(encoding="utf-8") != want_ref:
        stale.append(REF.as_posix())
        if not check:
            ref.parent.mkdir(parents=True, exist_ok=True)
            ref.write_text(want_ref, encoding="utf-8")
    task = repo / TASK
    text = task.read_text(encoding="utf-8")
    want_task = _splice(text, task_section())
    if want_task != text:
        stale.append(TASK.as_posix())
        if not check:
            task.write_text(want_task, encoding="utf-8")
    return stale
