// Regenerates src/doors.js from design/routes.yaml `doors:` (door keys and their job keys).
// Run: node tools/relay/gen-doors.mjs [--check]   (the test suite runs --check logic)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
export const ROUTES = join(here, "..", "..", "design", "routes.yaml");
export const OUT = join(here, "src", "doors.js");

export function parseDoors(text) {
  const doors = {};
  let inDoors = false, door = null, inJobs = false;
  for (const line of text.split("\n")) {
    if (/^\S/.test(line)) { inDoors = line.startsWith("doors:"); door = null; continue; }
    if (!inDoors) continue;
    let m = line.match(/^  ([A-Za-z0-9_]+):/);
    if (m) { door = m[1]; doors[door] = []; inJobs = false; continue; }
    m = line.match(/^    ([A-Za-z0-9_]+):/);
    if (m) { inJobs = m[1] === "jobs"; continue; }
    m = line.match(/^      ([A-Za-z0-9_]+):/);
    if (m && door && inJobs) doors[door].push(m[1]);
  }
  return doors;
}

export function render(doors) {
  return "// GENERATED by tools/relay/gen-doors.mjs from design/routes.yaml doors. Do not edit.\n" +
    "export const DOORS = " + JSON.stringify(doors, null, 0) + ";\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render(parseDoors(readFileSync(ROUTES, "utf8")));
  if (process.argv.includes("--check")) {
    const have = readFileSync(OUT, "utf8");
    if (have !== want) { console.error("doors.js stale: run node tools/relay/gen-doors.mjs"); process.exit(1); }
    console.log("doors.js in sync");
  } else { writeFileSync(OUT, want); console.log("wrote", OUT); }
}
