// Regenerates src/doors.js (relay), scripts/data/bug_doors.gd (game category check) and scripts/data/bug_doors.json
// (Report Bug Door/Job picker names and one-line descriptions) from design/routes.yaml `doors:` and the docs it names.
// Run: node tools/relay/gen-doors.mjs [--check]   (the test suite runs --check logic)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
export const ROUTES = join(here, "..", "..", "design", "routes.yaml");
export const OUT = join(here, "src", "doors.js");
export const GD_OUT = join(here, "..", "..", "scripts", "data", "bug_doors.gd");
export const JSON_OUT = join(here, "..", "..", "scripts", "data", "bug_doors.json");
const REPO = join(here, "..", "..");

export function parseDoors(text) {
  const doors = {};
  let inDoors = false, door = null, inJobs = false;
  for (const line of text.split("\n")) {
    if (/^\S/.test(line)) { inDoors = line.startsWith("doors:"); door = null; continue; }
    if (!inDoors) continue;
    let m = line.match(/^  ([A-Za-z0-9_]+):/);
    if (m) { door = m[1]; doors[door] = []; inJobs = false; continue; }
    m = line.match(/^    ([A-Za-z0-9_]+):/);
    if (m) { inJobs = m[1] === "jobs"; continue; }
    m = line.match(/^      ([A-Za-z0-9_]+):/);
    if (m && door && inJobs) doors[door].push(m[1]);
  }
  return doors;
}

export function render(doors) {
  return "// GENERATED by tools/relay/gen-doors.mjs from design/routes.yaml doors. Do not edit.\n" +
    "export const DOORS = " + JSON.stringify(doors, null, 0) + ";\n";
}

// Same doors for the game: GDScript tabs, a const Dictionary of door -> job keys.
export function renderGd(doors) {
  const rows = Object.entries(doors).map(([d, jobs]) => "\t\"" + d + "\": [" + jobs.map((j) => "\"" + j + "\"").join(", ") + "],");
  return "extends Object\n\n## GENERATED by tools/relay/gen-doors.mjs from design/routes.yaml doors. Do not edit.\n" +
    "## Report Bug categories must be a door or door.job from here (the relay refuses others).\n\n" +
    "const DOORS: Dictionary = {\n" + rows.join("\n") + "\n}\n";
}

// Door and job docs: file paths and each door's read_when, in routes.yaml order.
export function parseDocs(text) {
  const out = {};
  let inDoors = false, door = null, inJobs = false;
  for (const line of text.split("\n")) {
    if (/^\S/.test(line)) { inDoors = line.startsWith("doors:"); door = null; continue; }
    if (!inDoors) continue;
    let m = line.match(/^  ([A-Za-z0-9_]+):/);
    if (m) { door = m[1]; out[door] = { file: "", read_when: "", jobs: {} }; inJobs = false; continue; }
    m = line.match(/^    ([A-Za-z0-9_]+):\s*(.*)$/);
    if (m && door) {
      inJobs = m[1] === "jobs";
      if (m[1] === "file") out[door].file = m[2].trim();
      if (m[1] === "read_when") out[door].read_when = m[2].trim().replace(/^"|"$/g, "");
      continue;
    }
    m = line.match(/^      ([A-Za-z0-9_]+):\s*(\S*)/);
    if (m && door && inJobs) out[door].jobs[m[1]] = m[2];
  }
  return out;
}

// A doc's H1 (the picker name) and its "Read when:" line (the description). Missing doc: the key, no description.
export function docHead(read, file, key) {
  let text = "";
  try { text = file ? read(file) : ""; } catch { text = ""; }
  const h1 = (text.match(/^# (.+)$/m) || [])[1];
  const rw = (text.match(/^Read when:\s*(.+?)\s*$/m) || [])[1];
  const name = (h1 || key.replace(/_/g, " ")).trim();
  return { name: name.charAt(0).toUpperCase() + name.slice(1), about: (rw || "").trim() };
}

// Picker data for the game: doors in routes.yaml order, each with its jobs. A door's description is its routes.yaml
// read_when, falling back to its doc's "Read when:"; a job's is its doc's "Read when:".
export function pickerData(text, read = (f) => readFileSync(join(REPO, f), "utf8")) {
  const docs = parseDocs(text);
  const doors = Object.entries(docs).map(([key, d]) => {
    const head = docHead(read, d.file, key);
    const jobs = Object.entries(d.jobs).map(([jk, jf]) => ({ key: jk, ...docHead(read, jf, jk) }));
    return { key, name: head.name, about: d.read_when || head.about, jobs };
  });
  return { about: "GENERATED by tools/relay/gen-doors.mjs from design/routes.yaml doors and their docs. Do not edit.", doors };
}

export function renderJson(data) {
  return JSON.stringify(data, null, 1) + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = readFileSync(ROUTES, "utf8");
  const doors = parseDoors(text);
  const outs = [[OUT, render(doors)], [GD_OUT, renderGd(doors)], [JSON_OUT, renderJson(pickerData(text))]];
  if (process.argv.includes("--check")) {
    const stale = outs.filter(([f, want]) => readFileSync(f, "utf8") !== want);
    if (stale.length) { console.error("stale: " + stale.map(([f]) => f).join(", ") + ": run node tools/relay/gen-doors.mjs"); process.exit(1); }
    console.log("doors.js, bug_doors.gd and bug_doors.json in sync");
  } else { for (const [f, want] of outs) { writeFileSync(f, want); console.log("wrote", f); } }
}
